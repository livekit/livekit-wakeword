"""Generate lkww_tables.h: analysis window + sparse mel filterbank of the v2 log-mel front end.

  uv run python client/esp32/tools/gen_tables.py > client/esp32/livekit_wakeword/src/lkww_tables.h

Must match `livekit.wakeword_train.nn.LogMel` (n_fft 512, right-aligned 400-sample Hann, hop 160,
40 mels, librosa Slaney filters 40-7600 Hz).
"""

import librosa
import numpy as np

N_FFT, WIN, N_MELS = 512, 400, 40
w = np.zeros(N_FFT, np.float32)
w[N_FFT - WIN :] = np.hanning(WIN + 2)[1:-1]
fb = librosa.filters.mel(sr=16000, n_fft=N_FFT, n_mels=N_MELS, fmin=40, fmax=7600)
fb = fb.astype(np.float32)

start, length, weights = [], [], []
for row in fb:
    nz = np.nonzero(row)[0]
    start.append(int(nz[0]))
    length.append(int(nz[-1] - nz[0] + 1))
    weights.extend(row[nz[0] : nz[-1] + 1].tolist())


def floats(xs: list[float]) -> str:
    rows = [xs[i : i + 6] for i in range(0, len(xs), 6)]
    return ",\n".join("  " + ", ".join(f"{x:.9e}f" for x in r) for r in rows)


print("/* Generated by client/esp32/tools/gen_tables.py -- do not edit. */")
print("#ifndef LKWW_TABLES_H\n#define LKWW_TABLES_H\n")
print(f"#define LKWW_WIN_OFFSET {N_FFT - WIN} /* window is zero before this sample */")
print(f"#define LKWW_N_WEIGHTS {len(weights)}\n")
print(f"static const float lkww_window[{WIN}] = {{\n{floats(w[N_FFT - WIN :].tolist())}\n}};\n")
print(f"static const unsigned short lkww_mel_start[{N_MELS}] = {{{', '.join(map(str, start))}}};")
print(f"static const unsigned short lkww_mel_len[{N_MELS}] = {{{', '.join(map(str, length))}}};")
print(f"static const float lkww_mel_weights[{len(weights)}] = {{\n{floats(weights)}\n}};\n")
print("#endif")
